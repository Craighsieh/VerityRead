const messages: Record<SupportedLocale, LocaleMessages> = {
  en,
  zh_TW: zhTW,
  zh_CN: zhCN,
  ja,
  ko,
};

export function resolveLocale(rawLocale?: string): SupportedLocale {
  const raw =
    rawLocale ??
    (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage
      ? chrome.i18n.getUILanguage()
      : 'en');
  const locale = raw.replace('-', '_').toLowerCase();
  if (locale.startsWith('ja')) return 'ja';
  if (locale.startsWith('ko')) return 'ko';
  if (
    locale === 'zh_tw' ||
    locale === 'zh_hk' ||
    locale === 'zh_mo' ||
    locale.includes('hant')
  ) {
    return 'zh_TW';
  }
  if (locale.startsWith('zh')) return 'zh_CN';
  return 'en';
}

export function t(
  key: MessageKey,
  values: Record<string, string | number> = {},
  locale = resolveLocale(),
): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[locale][key],
  );
}

export function productName(locale = resolveLocale()): string {
  return messages[locale].productName;
}
